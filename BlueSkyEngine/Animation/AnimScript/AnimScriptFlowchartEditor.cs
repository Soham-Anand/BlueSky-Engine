/// <summary>
/// Visual node representing an animation state
/// </summary>
internal class StateNode
{
    public AnimState State { get; set; } = null!;
    public Vector2 Position { get; set; }
}

/// <summary>
/// Visual edge representing a transition
/// </summary>
internal class TransitionEdge
{
    public StateNode From { get; set; } = null!;
    public StateNode To { get; set; } = null!;
    public AnimTransition Transition { get; set; } = null!;
}
